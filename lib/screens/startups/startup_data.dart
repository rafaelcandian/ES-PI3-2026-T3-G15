class StartupData {
  final String title;
  final String subtitle;
  final String tag;
  final String equity;
  final String tokens;
  final String tokenValue;
  final double progress;
  final String goal;
  final String image;

  const StartupData({
    required this.title,
    required this.subtitle,
    required this.tag,
    required this.equity,
    required this.tokens,
    required this.tokenValue,
    required this.progress,
    required this.goal,
    required this.image,
  });
}